const struct font_glyph *font_20x32_get_glyph(char c)
{
    switch (c) {
        case '0': return &font_glyphs[FONT_CHAR_0];
        case '1': return &font_glyphs[FONT_CHAR_1];
        case '2': return &font_glyphs[FONT_CHAR_2];
        case '3': return &font_glyphs[FONT_CHAR_3];
        case '4': return &font_glyphs[FONT_CHAR_4];
        case '5': return &font_glyphs[FONT_CHAR_5];
        case '6': return &font_glyphs[FONT_CHAR_6];
        case '7': return &font_glyphs[FONT_CHAR_7];
        case '8': return &font_glyphs[FONT_CHAR_8];
        case '9': return &font_glyphs[FONT_CHAR_9];
        case ':': return &font_glyphs[FONT_CHAR_COLON];
        default:  return NULL;
    }
}

uint16_t font_20x32_get_text_width(const char *text)
{
    uint16_t width = 0;
    
    while (*text != '\0') {
        const struct font_glyph *glyph = font_20x32_get_glyph(*text);
        if (glyph != NULL) {
            width += glyph->width;
        }
        text++;
    }
    
    return width;
}
